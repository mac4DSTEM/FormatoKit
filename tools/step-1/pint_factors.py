#!/usr/bin/env python3
"""Writes Sources/FormatoCore/FormatoUnitsFactors.swift: Pint 0.26.1's conversion factors between the SI-prefixed forms of
a base unit, for powers +1 and -1, as Pint computes them (`Quantity(1.0, src).to(dst).magnitude`) (D12: tolerance allowed; the output is exact today).

    References/rsciio-venv/bin/python -I -B tools/step-1/pint_factors.py

Why a table: Pint derives each factor from its definition file through its root-unit machinery, and the result is not the
quotient of the two prefix scales (1e-30 m -> 1e-15 m is 9.999999999999999e-16, not 1e-15). A conversion of `value` from
src to dst is `value * factor(src, dst)` exactly (checked here on a seeded sweep before anything is written). The factors
of "meter" and "second" are checked to be identical, so one table per power serves every base FormatoUnits accepts.
Byte-reproducible; stops on any disagreement.
"""
import json, math, itertools, sys
from pathlib import Path
import numpy as np
import pint

ROOT = Path(__file__).resolve().parents[2]
u = pint.UnitRegistry()
assert pint.__version__ == "0.26.1", pint.__version__
pre = {}
for p in u._prefixes.values():
    try:
        s = p.converter.scale
        l = int(math.log10(s))
        if l == math.log10(s):
            pre[l] = (p.name, p.symbol)
    except Exception:
        pre[0] = ("", "")
powers = sorted(pre)

def table(base, power):
    out = []
    for a, b in itertools.product(powers, repeat=2):
        src, dst = pre[a][0] + base, pre[b][0] + base
        if power < 0:
            src, dst = "1/" + src, "1/" + dst
        out.append(u.Quantity(1.0, src).to(dst).magnitude)
    return out

pos, neg = table("meter", 1), table("meter", -1)
if pos != table("second", 1) or neg != table("second", -1):
    sys.exit("meter and second tables differ")
rng = np.random.default_rng(7)
for x in 10.0 ** rng.uniform(-14, 6, 300):
    for a, b in ((0, -9), (0, -6), (-9, -6), (0, -12), (-3, 3)):
        for power, tab in ((1, pos), (-1, neg)):
            src, dst = pre[a][0] + "meter", pre[b][0] + "meter"
            if power < 0:
                src, dst = "1/" + src, "1/" + dst
            got = u.Quantity(float(x), src).to(dst).magnitude
            if got != float(x) * tab[powers.index(a) * len(powers) + powers.index(b)]:
                sys.exit(f"value*factor differs from .to() at {x} {src}->{dst}")

def hexes(t):
    lines, row = [], []
    for v in t:
        row.append("0x%016x" % np.float64(v).view(np.uint64))
        if len(row) == 5:
            lines.append("        " + ", ".join(row) + ","); row = []
    if row:
        lines.append("        " + ", ".join(row) + ",")
    return "\n".join(lines)

text = f'''// GENERATED by tools/step-1/pint_factors.py from Pint {pint.__version__} (BSD-3-Clause, the Pint authors); do not edit.
// Pint's conversion factor between two SI-prefixed forms of one base unit (meter or second: identical), as the IEEE-754
// bits of `Quantity(1.0, src).to(dst).magnitude`. Row = source prefix, column = destination prefix, both in the order of
// `powers` below. `value * factor` is Pint's `.to()` exactly (checked by the generator and by gate U1).

package nonisolated enum FormatoUnitsFactors {{
    /// The SI prefix powers Pint's registry defines, ascending ({len(powers)}).
    package static let powers: [Int] = {powers}
    /// Pint's prefix symbols, same order ("" for none; micro is U+03BC).
    package static let symbols: [String] = {json.dumps([pre[p][1] for p in powers], ensure_ascii=False)}
    /// Power +1 (m, s): {len(pos)} factors.
    package static let positive: [UInt64] = [
{hexes(pos)}
    ]
    /// Power -1 (1/m, 1/s): {len(neg)} factors.
    package static let negative: [UInt64] = [
{hexes(neg)}
    ]
}}
'''
(ROOT / "Sources/FormatoCore/FormatoUnitsFactors.swift").write_text(text, encoding="utf-8")
print(f"FormatoUnitsFactors.swift: {len(powers)} prefixes, {len(pos)} + {len(neg)} factors")
