#!/usr/bin/env python3
"""Pins RosettaSciIO's reading of the Velox title review files.

    References/rsciio-venv/bin/python -I -B tools/velox-titles/refuter_pins.py
        writes Tests/FormatoCoreTests/Fixtures/step-3-refuter-pins.json from Tests/FormatoEMDTests/Fixtures/velox-titles-refuter/*.emd

The files were generated by the step-3 review (on f66bd60) from tools/velox-titles/make_velox_titles.py's layout,
each with one change: a Detectors map RosettaSciIO's `_get_detector_metadata_dict` raises on, an Operations / Displays /
Features root dataset, a missing Acquisition or CustomProperties, a Version without its key or with a zero-width space,
and two that RosettaSciIO reads (a string CustomProperties, a no-break space around the version). Step 1's Velox record per
file (`raises`, or each image's dtype, bytes and title); two builds in the process must agree.
"""
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIR = ROOT / "Tests" / "FormatoEMDTests" / "Fixtures" / "velox-titles-refuter"
OUT = ROOT / "Tests" / "FormatoCoreTests" / "Fixtures" / "step-3-refuter-pins.json"


def main():
    import h5py
    import numpy as np
    import pint
    spec = importlib.util.spec_from_file_location("step1_pins", ROOT / "tools" / "dm-velox-pins" / "pins.py")
    step1 = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(step1)
    R = step1.load_rsciio()

    def build():
        out = step1.header(np, h5py, pint, "step-3-refuter")
        out["generator"] = "tools/velox-titles/refuter_pins.py"
        out["files"] = [step1.velox_file(p, p.name, "step-3-refuter", R, np, h5py) for p in sorted(DIR.glob("*.emd"))]
        return step1.dump(out), out["files"]

    (a, files), (b, _) = build(), build()
    if a != b:
        step1.die("two builds differ")
    OUT.write_text(a)
    print(f"velox-titles refuter pins: {len(files)} files, {sum(1 for f in files if f['raises'])} raise in RosettaSciIO -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
