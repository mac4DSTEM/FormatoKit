"""HDF5 root-attribute fixtures and h5py pins for FormatoHDF5.HDF5RootAttributes.

    <suite>/References/FormatoKit/rsciio-venv/bin/python -I -B tools/hdf5-write/generate.py

Writes with h5py (the reference HDF5 binding) the files the reader must read or refuse, and records how h5py reads the golden file the
kit's own writer produced (Tests/FormatoHDF5Tests/Fixtures/root-attributes/kit-written.h5, regenerated by
`FORMATO_WRITE_GOLDEN=1 swift test --filter HDF5RootAttributesTests`, a change on purpose): attribute bytes, dtype, character set,
string padding, rank, and the superblock version. The test compares a fresh write with the golden by size, signature, superblock version and the attributes read back (HDF5 stamps times, so not byte for byte).
"""
import hashlib, json, pathlib
import h5py
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'Tests/FormatoHDF5Tests/Fixtures/root-attributes'
OUT.mkdir(parents=True, exist_ok=True)


def fixed_utf8(f, name, text, nullpad=True):
    data = text.encode() if text else b'\0'
    t = h5py.h5t.C_S1.copy()
    t.set_size(len(data))
    t.set_cset(h5py.h5t.CSET_UTF8)
    t.set_strpad(h5py.h5t.STR_NULLPAD if nullpad else h5py.h5t.STR_NULLTERM)
    space = h5py.h5s.create(h5py.h5s.SCALAR)
    a = h5py.h5a.create(f.id, name.encode(), t, space)
    a.write(np.frombuffer(data, dtype=f'S{len(data)}').reshape(()), mtype=t)


# h5py-written, read by the kit: the same attributes in the shapes the reader takes and refuses.
with h5py.File(OUT / 'h5py-written.h5', 'w', libver=('v108', 'latest')) as f:
    fixed_utf8(f, 'identity', '1')
    fixed_utf8(f, 'text', 'Å 日本 😀 text')
    fixed_utf8(f, 'empty', '')
    fixed_utf8(f, 'long', 'x' * 30000)
    f.attrs.create('ascii', np.bytes_('plain ascii'))          # h5py's default: fixed-length, ASCII character set, null padded
with h5py.File(OUT / 'variable-length.h5', 'w') as f:
    f.attrs['text'] = 'a variable-length string'
with h5py.File(OUT / 'array-attribute.h5', 'w') as f:
    f.attrs['text'] = np.array([b'ab', b'cd'], dtype='S2')
with h5py.File(OUT / 'not-a-string.h5', 'w') as f:
    f.attrs['text'] = 5
with h5py.File(OUT / 'embedded-nul.h5', 'w') as f:
    f.attrs.create('text', np.bytes_(b'ab\0cd'), dtype='S5')
with h5py.File(OUT / 'invalid-utf8.h5', 'w') as f:
    f.attrs.create('text', np.bytes_(b'\xff\xfe'), dtype='S2')
with h5py.File(OUT / 'dense.h5', 'w', libver='latest') as f:
    for i in range(40):                                        # past the compact limit: dense attribute storage
        f.attrs[f'a{i:02d}'] = np.bytes_('v')
(OUT / 'not-hdf5.h5').write_bytes(b'this is not an HDF5 file\n' * 4)

golden = OUT / 'kit-written.h5'
if golden.exists():
    pins = {'attributes': {}}
    with h5py.File(golden, 'r') as f:
        pins['groups'] = len(list(f.keys()))
        pins['superblock_version'] = f.id.get_create_plist().get_version()[0]
        for name in f.attrs:
            a = h5py.h5a.open(f.id, name.encode())
            t = a.get_type()
            raw = np.empty((), dtype=f'S{t.get_size()}')
            a.read(raw, mtype=t)
            data = bytes(raw.tobytes())
            pins['attributes'][name] = {'bytes_hex': data.hex() if len(data) <= 200 else None, 'sha256': hashlib.sha256(data).hexdigest(), 'size': t.get_size(), 'cset': t.get_cset(),
                                         'strpad': t.get_strpad(), 'rank': a.get_space().get_simple_extent_ndims(),
                                         'class': 'string' if t.get_class() == h5py.h5t.STRING else 'other'}
    (OUT / 'kit-written.h5py.json').write_text(json.dumps(pins, indent=1, sort_keys=True) + '\n')
